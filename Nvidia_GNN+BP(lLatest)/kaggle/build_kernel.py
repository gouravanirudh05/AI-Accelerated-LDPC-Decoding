def bundle():
    buf = io.BytesIO()
    skip = lambda ti: None if ("__pycache__" in ti.name or ti.name.endswith(".pyc")) else ti
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for d in FOLDERS:
            t.add(os.path.join(ROOT, d), d, filter=skip)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    extra = ["--quick"] if "--quick" in sys.argv else []
    b = bundle()
    for name, k in KERNELS.items():
        d = os.path.join(ROOT, "kaggle", name)
        os.makedirs(d, exist_ok=True)
        slug = k["title"].lower().replace(" ", "-")
        fname = f"{slug}.py"
        runs = [(s, a + [x for x in extra if x not in a]) for s, a in k["runs"]]
        with open(os.path.join(d, fname), "w") as f:
            f.write(TEMPLATE.format(title=k["title"], folders=", ".join(FOLDERS), bundle=b, runs=runs))
        meta = dict(id=f"{k.get('user', USER)}/{slug}", title=k["title"], code_file=fname, language="python",
                    kernel_type="script", is_private=True, enable_gpu=k["gpu"], enable_tpu=False,
                    enable_internet=True, dataset_sources=[], kernel_sources=[],
                    competition_sources=[], model_sources=[])
        if k["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        with open(os.path.join(d, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        print(f"built {d}/{fname} ({os.path.getsize(os.path.join(d, fname)) // 1024} KiB)")


if __name__ == "__main__":
    main()
