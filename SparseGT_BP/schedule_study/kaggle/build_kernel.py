"""Build self-contained Kaggle kernels for the BP-SGT schedule study.

Same mechanism as SparseGT_BP/kaggle/build_kernel.py: the sources (SparseGT_BP/sgt,
SparseGT_BP/schedule_study and the BP-GNN project's common/, normal_ldpc/, 5g_ldpc/,
final/ incl. code matrices) are embedded as a base64 tarball, together with the
trained final BP-SGT checkpoints of the kernel's codes (about 0.3 MB each), so no
Kaggle input is needed. One run queue per GPU (T4 x2: in parallel); afterwards the
"post" commands (plots / tables, CPU only) run once over all results. Results land
in /kaggle/working/results/schedule_study/<task>.

Kernels
  smoke            CPU, a few minutes: every script with --quick on MacKay (204,102)
  sched_a..d       tasks 1, 2, 4: all BP schedules on all 10 codes (inference only,
                   same code split over accounts as the BP-SGT final runs)
  single_a..d      task 5 with a trained single-stage model (80 min per code) + the
                   inference-only single-stage variants; tasks 2 and 4 plots on it too

  python kaggle/build_kernel.py [--only name,...]     # writes kaggle/<name>/{script,metadata}
  KAGGLE_API_TOKEN=... kaggle kernels push -p kaggle/<name>
"""

import argparse
import base64
import glob
import io
import json
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
STUDY = os.path.dirname(HERE)
SGT = os.path.dirname(STUDY)
REPO = os.path.dirname(SGT)
NV = "Nvidia_GNN+BP(lLatest)"
SOURCES = [(os.path.join(SGT, "sgt"), "SparseGT_BP/sgt"),
           (STUDY, "SparseGT_BP/schedule_study")] + \
          [(os.path.join(REPO, NV, d), f"{NV}/{d}") for d in ("common", "normal_ldpc", "5g_ldpc", "final")]
A, B, C = "gouravanirudh", "gouravanirudh1105", "gourasri"
D = "arnavoruganty"  # lent for this project only (same accounts as the BP-SGT runs)

P = "SparseGT_BP/schedule_study/"
T1 = P + "task1_bp_schedules/run_schedules.py"
T5 = P + "task5_single_vs_interleaved/run_single_vs_interleaved.py"
RES = "/kaggle/working/results/schedule_study/"


def post(task, extra=()):
    """Plot / table commands over the traces of one task folder; tasks 2 and 4 write into
    their own folders (task2_stopping_points/<source task>, task4_avg_bp_iterations/<source task>)."""
    d = RES + task
    src = task.split("_")[0]
    return list(extra) + [
        (P + "task2_stopping_points/plot_stopping_points.py", ["--traces", d, "--out", f"{RES}task2_stopping_points/{src}"]),
        (P + "task4_avg_bp_iterations/avg_iterations.py", ["--traces", d, "--out", f"{RES}task4_avg_bp_iterations/{src}"])]


POST1 = post("task1_bp_schedules", [(P + "task1_bp_schedules/plot_schedules.py", ["--traces", RES + "task1_bp_schedules"])])
POST5 = post("task5_single_vs_interleaved",
             [(P + "task5_single_vs_interleaved/compare.py", ["--traces", RES + "task5_single_vs_interleaved"])])

KERNELS = {
    "smoke": dict(title="SGT Schedule Smoke", user=A, gpu=False, codes=["mackay_204_102"], queues=[[
        (T1, ["--quick", "--codes", "mackay_204_102"]),
        (T5, ["--quick", "--codes", "mackay_204_102", "--train-minutes", "0.3"])]],
        post=POST1 + POST5),
}
# same split as the BP-SGT final runs: 10 codes over 4 accounts x 2 GPU queues
SPLIT = {
    A: [["mackay_96_48", "ccsds_128_64"], ["5G_BG1_k1056_n1408"]],
    B: [["mackay_204_102"], ["5G_BG2_k64_n128", "5G_BG2_k128_n256"]],
    C: [["mackay_408_204"], ["5G_BG2_k256_n512"]],
    D: [["wimax_576_288"], ["5G_BG1_k528_n704"]],
}
for i, (user, queues) in enumerate(SPLIT.items()):
    s = "abcd"[i]
    codes = [c for q in queues for c in q]
    KERNELS[f"sched_{s}"] = dict(title=f"SGT Schedule Study {s.upper()}", user=user, gpu=True, codes=codes,
                                 queues=[[(T1, ["--codes", ",".join(q)])] for q in queues], post=POST1)
    KERNELS[f"single_{s}"] = dict(title=f"SGT Single Stage {s.upper()}", user=user, gpu=True, codes=codes,
                                  queues=[[(T5, ["--codes", ",".join(q), "--train-minutes", "80"])] for q in queues],
                                  post=POST5)


TEMPLATE = '''"""Kaggle entry point (generated by SparseGT_BP/schedule_study/kaggle/build_kernel.py): {title}."""

import base64
import io
import os
import shutil
import subprocess
import sys
import tarfile
import threading

BUNDLE = {bundle!r}
SRC = "/kaggle/working/src"
QUEUES = {queues!r}
POST = {post!r}

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as t:
    t.extractall(SRC, filter="data")
if shutil.which("nvidia-smi"):
    subprocess.run(["nvidia-smi"], check=False)
try:
    import torch
    ngpu = torch.cuda.device_count()
except Exception:
    ngpu = 0
rcs = [0] * len(QUEUES)


def run_queue(i):
    env = dict(os.environ)
    if ngpu > 1:
        env["CUDA_VISIBLE_DEVICES"] = str(i % ngpu)
    for script, args in QUEUES[i]:
        print(f"[queue {{i}}] {{script}} {{args}}", flush=True)
        rcs[i] |= subprocess.run([sys.executable, os.path.join(SRC, script)] + args, env=env).returncode


if ngpu > 1:
    threads = [threading.Thread(target=run_queue, args=(i,)) for i in range(len(QUEUES))]
    for th in threads:
        th.start()
    for th in threads:
        th.join()
else:
    for i in range(len(QUEUES)):
        run_queue(i)
for script, args in POST:
    print(f"[post] {{script}} {{args}}", flush=True)
    rcs[0] |= subprocess.run([sys.executable, os.path.join(SRC, script)] + args).returncode
shutil.rmtree(SRC, ignore_errors=True)
print("exit codes", rcs)
sys.exit(max(rcs))
'''


def checkpoints(codes):
    out = []
    for c in codes:
        hits = sorted(glob.glob(os.path.join(SGT, "results", "kaggle_final_*", "results", "*", f"*_{c}_sgt.pt")))
        assert hits, f"no final checkpoint for {c}"
        out.append((hits[0], os.path.relpath(hits[0], REPO)))
    return out


def bundle(codes):
    buf = io.BytesIO()
    excl = ("SparseGT_BP/schedule_study/kaggle", "SparseGT_BP/schedule_study/out")
    skip = lambda ti: None if ("__pycache__" in ti.name or ti.name.startswith(excl)
                               or ti.name.endswith((".pyc", ".pt"))) else ti
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for src, arc in SOURCES:
            t.add(os.path.normpath(src), arc, filter=skip)
        for src, arc in checkpoints(codes):
            t.add(src, arc)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default=None, help="comma-separated kernel names (default: all)")
    args = ap.parse_args()
    names = args.only.split(",") if args.only else list(KERNELS)
    for name in names:
        k = KERNELS[name]
        d = os.path.join(HERE, name)
        os.makedirs(d, exist_ok=True)
        slug = k["title"].lower().replace(" ", "-")
        fname = f"{slug}.py"
        with open(os.path.join(d, fname), "w") as f:
            f.write(TEMPLATE.format(title=k["title"], bundle=bundle(k["codes"]), queues=k["queues"], post=k["post"]))
        meta = dict(id=f"{k['user']}/{slug}", title=k["title"], code_file=fname, language="python",
                    kernel_type="script", is_private=True, enable_gpu=k["gpu"], enable_tpu=False,
                    enable_internet=True, dataset_sources=[], kernel_sources=[],
                    competition_sources=[], model_sources=[])
        if k["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        with open(os.path.join(d, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        print(f"built {d}/{fname} ({os.path.getsize(os.path.join(d, fname)) // 1024} KiB) -> {meta['id']}")


if __name__ == "__main__":
    main()
