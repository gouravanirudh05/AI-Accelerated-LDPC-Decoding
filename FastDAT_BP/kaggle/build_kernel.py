"""Build the self-contained Kaggle kernels of the fast BP-DAT benchmark.

Same scheme as the other folders: the sources (FastDAT_BP, DualAttention_BP/dat,
PooledGNN_BP/pgnn, SparseGT_BP/sgt and the BP-GNN project's common/,
normal_ldpc/, 5g_ldpc/, final/) and the trained BP-GNN and BP-SGT checkpoints of
the benchmarked codes (committed in the repo) are embedded as a base64 tarball.
ONE process on GPU 0, so every row of the report comes from the same session.

Kernels
  fastdat_smoke  CPU, minutes: equivalence tests on 5G (128,64) + a --quick benchmark
  fastdat_t4     T4: benchmark on 5G (704,528) and (1408,1056)

  python FastDAT_BP/kaggle/build_kernel.py [--dat-source user/kernel-slug ...]
  kaggle kernels push -p FastDAT_BP/kaggle/fastdat_t4
  kaggle kernels output gouravanirudh/fastdat-ldpc-t4 -p FastDAT_BP/results/kaggle_fastdat_t4

BP-DAT is benchmarked untrained (= BP with restarts) unless a trained checkpoint
final_dat_*_<code>_dat.pt is mounted: pass the DualAttention_BP final kernels that
trained it with --dat-source (e.g. gouravanirudh/dat-ldpc-final-a for 5G 1408),
and they are added as kernel sources (read from /kaggle/input).
"""

import argparse
import base64
import glob
import io
import json
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPO = os.path.dirname(ROOT)
NV = "Nvidia_GNN+BP(lLatest)"
SOURCES = [(os.path.join(ROOT, p), f"FastDAT_BP/{p}") for p in ("fastdat", "tests", "bench_t4.py")] + \
          [(os.path.join(REPO, "DualAttention_BP", "dat"), "DualAttention_BP/dat"),
           (os.path.join(REPO, "PooledGNN_BP", "pgnn"), "PooledGNN_BP/pgnn"),
           (os.path.join(REPO, "SparseGT_BP", "sgt"), "SparseGT_BP/sgt")] + \
          [(os.path.join(REPO, NV, d), f"{NV}/{d}") for d in ("common", "normal_ldpc", "5g_ldpc", "final")]
CODES = ["5G_BG1_k528_n704", "5G_BG1_k1056_n1408"]
CKPT_PATTERNS = [f"{NV}/results/**/final_learned_*_{{c}}_bpgnn.pt", "SparseGT_BP/results/**/final_sgt_*_{c}_sgt.pt"]
USER = "gouravanirudh"

KERNELS = {
    "fastdat_smoke": dict(title="FastDAT LDPC Smoke", gpu=False, cmds=[
        ["FastDAT_BP/tests/test_equivalence.py", "--codes", "5G_BG2_k64_n128", "--frames", "32"],
        ["FastDAT_BP/bench_t4.py", "--quick", "--codes", "5G_BG2_k64_n128"]]),
    "fastdat_t4": dict(title="FastDAT LDPC T4", gpu=True, cmds=[
        ["FastDAT_BP/bench_t4.py", "--codes", ",".join(CODES)]]),
}

TEMPLATE = '''"""Kaggle entry point (generated by FastDAT_BP/kaggle/build_kernel.py): {title}."""

import base64
import io
import os
import shutil
import subprocess
import sys
import tarfile

BUNDLE = {bundle!r}
SRC = "/kaggle/working/src"
CMDS = {cmds!r}

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as t:
    t.extractall(SRC, filter="data")
if shutil.which("nvidia-smi"):
    subprocess.run(["nvidia-smi"], check=False)
env = dict(os.environ, CUDA_VISIBLE_DEVICES="0")
rc = 0
for cmd in CMDS:
    print("$", " ".join(cmd), flush=True)
    rc |= subprocess.run([sys.executable, os.path.join(SRC, cmd[0])] + cmd[1:], env=env).returncode
shutil.rmtree(SRC, ignore_errors=True)
print("exit code", rc)
sys.exit(rc)
'''


def checkpoints():
    out = []
    for c in CODES:
        for pat in CKPT_PATTERNS:
            hits = sorted(glob.glob(os.path.join(REPO, pat.format(c=c)), recursive=True))
            if hits:
                out.append(hits[0])
            else:
                print(f"warning: no checkpoint for {pat.format(c=c)}")
    return out


def bundle():
    buf = io.BytesIO()
    skip = lambda ti: None if ("__pycache__" in ti.name or ti.name.endswith((".pyc", ".pt"))) else ti
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for src, arc in SOURCES:
            t.add(os.path.normpath(src), arc, filter=skip)
        for p in checkpoints():
            t.add(p, os.path.relpath(p, REPO))
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dat-source", nargs="*", default=[], help="Kaggle kernels with trained BP-DAT checkpoints")
    args = ap.parse_args()
    b = bundle()
    for name, k in KERNELS.items():
        d = os.path.join(HERE, name)
        os.makedirs(d, exist_ok=True)
        slug = k["title"].lower().replace(" ", "-")
        fname = f"{slug}.py"
        with open(os.path.join(d, fname), "w") as f:
            f.write(TEMPLATE.format(title=k["title"], bundle=b, cmds=k["cmds"]))
        meta = dict(id=f"{USER}/{slug}", title=k["title"], code_file=fname, language="python",
                    kernel_type="script", is_private=True, enable_gpu=k["gpu"], enable_tpu=False,
                    enable_internet=True, dataset_sources=[], kernel_sources=args.dat_source if k["gpu"] else [],
                    competition_sources=[], model_sources=[])
        if k["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        with open(os.path.join(d, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        print(f"built {d}/{fname} ({os.path.getsize(os.path.join(d, fname)) // 1024} KiB) -> {meta['id']}")


if __name__ == "__main__":
    main()
