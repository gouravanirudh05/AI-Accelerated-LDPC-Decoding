"""Build self-contained Kaggle kernels for the BP-DAT experiments.

Same mechanism as PooledGNN_BP/kaggle/build_kernel.py: the sources (this
project's dat/, final/, BP-PGNN's pgnn/ (features, RWSE, training specs) and
the BP-GNN project's common/, normal_ldpc/, 5g_ldpc/, final/ incl. code
matrices) are embedded as a base64 tarball. One
run queue per GPU; on a T4 x2 session the queues run in parallel
(CUDA_VISIBLE_DEVICES = queue index). Results land in
/kaggle/working/results/<run tag>.

Kernels
  smoke              CPU, a few minutes: quick run on one normal and one 5G code (DAT and DAT-NB)
  final_a .. final_d main model DAT (final/dat_config.json) on all 10 codes,
                     same code split over accounts as the BP-SGT / BP-PGNN final runs
  abl_nb_a/b,        second candidate and ablation on MacKay 204, WiMAX 576, 5G 704, 5G 1408:
  abl_noself_a/b     non-backtracking cross branch (DAT-NB), and no global self-attention (DAT-NoSelf)

Training: 80 min per code, 160 min on codes with n >= 512 (as BP-PGNN), so the
longest queue (5G 1408: 160 min training + deep Monte Carlo) fits in a 12 h session.

  python kaggle/build_kernel.py [--only name,...]     # writes kaggle/<name>/{script,metadata}
  KAGGLE_API_TOKEN=... kaggle kernels push -p kaggle/<name>
"""

import argparse
import base64
import io
import json
import os
import tarfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NV = "Nvidia_GNN+BP(lLatest)"
SOURCES = [(os.path.join(ROOT, d), f"DualAttention_BP/{d}") for d in ("dat", "final")] + \
          [(os.path.join(ROOT, "..", "PooledGNN_BP", "pgnn"), "PooledGNN_BP/pgnn")] + \
          [(os.path.join(ROOT, "..", NV, d), f"{NV}/{d}") for d in ("common", "normal_ldpc", "5g_ldpc", "final")]
A, B, C = "gouravanirudh", "gouravanirudh1105", "gourasri"
D = "arnavoruganty"  # lent for this project only (same accounts as the BP-SGT runs)
FINAL = "DualAttention_BP/final/run_dat_final.py"


def final(group, codes, config="dat_config.json"):
    return FINAL, ["--group", group, "--codes", ",".join(codes), "--config", config]


N, G = "normal", "5g"
KERNELS = {
    "smoke": dict(title="DAT LDPC Smoke", user=A, gpu=False, queues=[[
        (FINAL, ["--quick", "--group", N, "--codes", "mackay_96_48"]),
        (FINAL, ["--quick", "--group", G, "--codes", "5G_BG2_k64_n128"]),
        (FINAL, ["--quick", "--group", G, "--codes", "5G_BG2_k64_n128", "--config", "dat_nb_config.json"])]]),
}
# final runs: 10 codes over 4 accounts x 2 GPU queues (split of the SparseGT_BP / PooledGNN_BP final runs)
FINAL_SPLIT = {
    A: [[(N, ["mackay_96_48"]), (N, ["ccsds_128_64"])], [(G, ["5G_BG1_k1056_n1408"])]],
    B: [[(N, ["mackay_204_102"])], [(G, ["5G_BG2_k64_n128"]), (G, ["5G_BG2_k128_n256"])]],
    C: [[(N, ["mackay_408_204"])], [(G, ["5G_BG2_k256_n512"])]],
    D: [[(N, ["wimax_576_288"])], [(G, ["5G_BG1_k528_n704"])]],
}
for i, (user, queues) in enumerate(FINAL_SPLIT.items()):
    KERNELS[f"final_{'abcd'[i]}"] = dict(
        title=f"DAT LDPC Final {'ABCD'[i]}", user=user, gpu=True,
        queues=[[final(g, c) for g, c in q] for q in queues])
# optional ablations (two kernels per config, two queues each)
for cfg, short in [("dat_nb_config.json", "nb"), ("dat_noself_config.json", "noself")]:
    for half, (user, qs) in enumerate([(C, [[(N, ["mackay_204_102"])], [(N, ["wimax_576_288"])]]),
                                       (D, [[(G, ["5G_BG1_k528_n704"])], [(G, ["5G_BG1_k1056_n1408"])]])]):
        KERNELS[f"abl_{short}_{'ab'[half]}"] = dict(
            title=f"DAT LDPC Abl {short.title()} {'AB'[half]}", user=user, gpu=True,
            queues=[[final(g, c, cfg) for g, c in q] for q in qs])


TEMPLATE = '''"""Kaggle entry point (generated by DualAttention_BP/kaggle/build_kernel.py): {title}."""

import base64
import io
import os
import shutil
import subprocess
import sys
import tarfile
import threading

BUNDLE = {bundle!r}
SRC = "/kaggle/working/src"
QUEUES = {queues!r}

with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as t:
    t.extractall(SRC, filter="data")
try:
    import pynvml  # noqa: F401
except ImportError:
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "nvidia-ml-py"], check=False)
if shutil.which("nvidia-smi"):
    subprocess.run(["nvidia-smi"], check=False)
try:
    import torch
    ngpu = torch.cuda.device_count()
except Exception:
    ngpu = 0
rcs = [0] * len(QUEUES)


def run_queue(i):
    env = dict(os.environ)
    if ngpu > 1:
        env["CUDA_VISIBLE_DEVICES"] = str(i % ngpu)
    for script, args in QUEUES[i]:
        print(f"[queue {{i}}] {{script}} {{args}}", flush=True)
        rcs[i] |= subprocess.run([sys.executable, os.path.join(SRC, script)] + args, env=env).returncode


if ngpu > 1:
    threads = [threading.Thread(target=run_queue, args=(i,)) for i in range(len(QUEUES))]
    for th in threads:
        th.start()
    for th in threads:
        th.join()
else:
    for i in range(len(QUEUES)):
        run_queue(i)
shutil.rmtree(SRC, ignore_errors=True)
print("exit codes", rcs)
sys.exit(max(rcs))
'''


def bundle():
    buf = io.BytesIO()
    skip = lambda ti: None if ("__pycache__" in ti.name or ti.name.endswith((".pyc", ".pt"))) else ti
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for src, arc in SOURCES:
            t.add(os.path.normpath(src), arc, filter=skip)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default=None, help="comma-separated kernel names (default: all)")
    args = ap.parse_args()
    b = bundle()
    names = args.only.split(",") if args.only else list(KERNELS)
    for name in names:
        k = KERNELS[name]
        d = os.path.join(ROOT, "kaggle", name)
        os.makedirs(d, exist_ok=True)
        slug = k["title"].lower().replace(" ", "-")
        fname = f"{slug}.py"
        with open(os.path.join(d, fname), "w") as f:
            f.write(TEMPLATE.format(title=k["title"], bundle=b, queues=k["queues"]))
        meta = dict(id=f"{k['user']}/{slug}", title=k["title"], code_file=fname, language="python",
                    kernel_type="script", is_private=True, enable_gpu=k["gpu"], enable_tpu=False,
                    enable_internet=True, dataset_sources=[], kernel_sources=k.get("sources", []),
                    competition_sources=[], model_sources=[])
        if k["gpu"]:
            meta["machine_shape"] = "NvidiaTeslaT4"
        with open(os.path.join(d, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        print(f"built {d}/{fname} ({os.path.getsize(os.path.join(d, fname)) // 1024} KiB) -> {meta['id']}")


if __name__ == "__main__":
    main()
