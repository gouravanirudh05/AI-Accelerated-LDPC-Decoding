"""Build the self-contained Kaggle kernel for the latency analysis (same scheme as
SparseGT_BP/kaggle/build_kernel.py: sources and code matrices embedded as a base64
tarball). ONE process on GPU 0, so every number in the report is from one session.

  python kaggle/build_kernel.py                     # writes kaggle/latency_t4/{script,metadata}
  kaggle kernels push -p kaggle/latency_t4
  kaggle kernels output gouravanirudh/ldpc-latency-t4 -p results/kaggle_latency_t4

The kernel reads the trained BP-SGT checkpoints of the final runs from the account's
own "SGT LDPC Final A" output (ccsds_128_64, 5G_BG1_k1056_n1408); the other codes
run with an untrained model (fixed-stage timing does not depend on the weights).
"""

import base64
import io
import json
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REPO = os.path.dirname(ROOT)
NV = "Nvidia_GNN+BP(lLatest)"
SOURCES = [(os.path.join(ROOT, p), f"Latency_Analysis/{p}") for p in ("lat", "run_latency.py", "cost_model.py")] + \
          [(os.path.join(REPO, "SparseGT_BP", "sgt"), "SparseGT_BP/sgt")] + \
          [(os.path.join(REPO, NV, d), f"{NV}/{d}") for d in ("common", "normal_ldpc", "5g_ldpc", "final")]
CODES = "ccsds_128_64,mackay_204_102,wimax_576_288,5G_BG1_k1056_n1408"
KERNELS = {
    "latency_t4": dict(title="LDPC Latency T4", user="gouravanirudh", sources=["gouravanirudh/sgt-ldpc-final-a"],
                       args=["--codes", CODES]),
    "latency_smoke": dict(title="LDPC Latency Smoke", user="gouravanirudh", sources=[],
                          args=["--codes", "5G_BG2_k64_n128", "--quick"]),
}

TEMPLATE = '''"""Kaggle entry point (generated by Latency_Analysis/kaggle/build_kernel.py): {title}."""

import base64
import io
import os
import subprocess
import sys
import tarfile

BUNDLE = {bundle!r}
SRC = "/kaggle/working/src"
with tarfile.open(fileobj=io.BytesIO(base64.b64decode(BUNDLE)), mode="r:gz") as t:
    t.extractall(SRC, filter="data")
import shutil
if shutil.which("nvidia-smi"):
    subprocess.run(["nvidia-smi"], check=False)
env = dict(os.environ, CUDA_VISIBLE_DEVICES="0")
cmd = [sys.executable, os.path.join(SRC, "Latency_Analysis", "run_latency.py")] + {args!r}
cmd += ["--cost-model"]
rc = subprocess.run(cmd, env=env).returncode
shutil.rmtree(SRC, ignore_errors=True)
sys.exit(rc)
'''


def bundle():
    buf = io.BytesIO()
    skip = lambda ti: None if ("__pycache__" in ti.name or ti.name.endswith((".pyc", ".pt"))) else ti
    with tarfile.open(fileobj=buf, mode="w:gz") as t:
        for src, arc in SOURCES:
            t.add(os.path.normpath(src), arc, filter=skip)
    return base64.b64encode(buf.getvalue()).decode()


def main():
    b = bundle()
    for name, k in KERNELS.items():
        d = os.path.join(HERE, name)
        os.makedirs(d, exist_ok=True)
        slug = "ldpc-" + k["title"].lower().replace(" ", "-").replace("ldpc-", "")
        fname = f"{slug}.py"
        with open(os.path.join(d, fname), "w") as f:
            f.write(TEMPLATE.format(title=k["title"], bundle=b, args=k["args"]))
        meta = dict(id=f"{k['user']}/{slug}", title=k["title"], code_file=fname, language="python",
                    kernel_type="script", is_private=True, enable_gpu=True, enable_tpu=False,
                    enable_internet=True, dataset_sources=[], kernel_sources=k["sources"],
                    competition_sources=[], model_sources=[], machine_shape="NvidiaTeslaT4")
        with open(os.path.join(d, "kernel-metadata.json"), "w") as f:
            json.dump(meta, f, indent=2)
        print(f"built {d}/{fname} ({os.path.getsize(os.path.join(d, fname)) // 1024} KiB) -> {meta['id']}")


if __name__ == "__main__":
    main()
